"""生成合成测试夹具（不含任何真实设计）。输出确定（固定时间戳、固定坐标和 ZIP_STORED（跨 zlib 版本一致）），可重复生成并比对。

模拟对象：嘉立创EDA 导出的 Gerber 压缩包（新格式 FSLAX45Y45 / 旧格式 FSLAX26Y26）以及原生 BOM / 坐标文件
（UTF-16 + 制表符、坐标值带 mm 后缀、行间空行）。数据全是虚构的：2 层 60×40mm 演示板，20 个位号，器件为通用阻容 + 两个虚构 IC。

用法：python tools/make_fixtures.py [--check]
  无参数：写入 tests/fixtures/
  --check：重新生成到内存并与磁盘文件逐字节比对，不一致退出 1（防止夹具被手改）
"""
