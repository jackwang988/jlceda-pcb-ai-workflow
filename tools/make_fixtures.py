ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "tests" / "fixtures"
ZIP_TIME = (2026, 1, 1, 0, 0, 0)  # 固定时间戳 → 字节级可复现

BOARD_W, BOARD_H = 60.0, 40.0
SYNTH_NOTE = "Synthetic fixture (not a real design); format modeled on EasyEDA Pro export"


# ───────────────────────── Gerber 生成 ─────────────────────────
class Fmt:
    def __init__(self, ints, decs):
        self.ints, self.decs = ints, decs
        self.scale = 10 ** decs

    def c(self, v):
        return str(int(round(v * self.scale)))

    def header(self, layer):
        return [f"G04 Layer: {layer}*", f"G04 {SYNTH_NOTE}*", "G04 Gerber Generator version 0.3*",
                "G04 Scale: 100 percent, Rotated: No, Reflected: No*", "G04 Dimensions in millimeters*",
                f"G04 Leading zeros omitted, absolute positions, {self.ints} integers and {self.decs} decimals*",
                "G04 Generated by custom config*", "G04 Copper Areas: 0*",
                f"%FSLAX{self.ints}{self.decs}Y{self.ints}{self.decs}*%", "%MOMM*%"]


def gerber(fmt, layer, apertures, sections, tail="M02*"):
    """apertures: [(no, 'C,0.2') ...]；sections: [(段名, [行...])]"""
    L = fmt.header(layer)
    L += [f"%ADD{n}{spec}*%" for n, spec in apertures]
    L.append("G75*")
    for name, lines in sections:
        L.append(f"G04 {name} Start*")
        L += lines
    L += ["", tail, ""]
    return "\n".join(L)


def flash(f, ap, pts):
    return [f"G54D{ap}*"] + [f"G01X{f.c(x)}Y{f.c(y)}D03*" for x, y in pts]


def polyline(f, ap, pts):
    out = [f"G54D{ap}*", f"G01X{f.c(pts[0][0])}Y{f.c(pts[0][1])}D02*"]
    out += [f"G01X{f.c(x)}Y{f.c(y)}D01*" for x, y in pts[1:]]
    return out


def region(f, pts):
    out = ["G36*", f"G01X{f.c(pts[0][0])}Y{f.c(pts[0][1])}D02*"]
    out += [f"G01X{f.c(x)}Y{f.c(y)}D01*" for x, y in pts[1:]] + ["G37*"]
    return out


def rect_pts(x0, y0, x1, y1):
    return [(x0, y0), (x1, y0), (x1, y1), (x0, y1), (x0, y0)]


PADS_TOP = [(8 + 4 * i, 8 + 3 * (i % 4)) for i in range(16)] + [(50, 30), (52, 30), (50, 33), (52, 33)]
PADS_BOT = [(12 + 3 * i, 20) for i in range(12)]
VIAS = [(10 + 3.5 * i, 14 + (i % 3)) for i in range(12)]
TRACKS = [[(8, 8), (8, 12), (20, 12)], [(12, 8), (12, 11), (30, 11)], [(16, 8), (16, 20), (40, 20)],
          [(20, 8), (20, 6), (44, 6)], [(24, 8), (24, 30)], [(28, 11), (28, 26), (46, 26)]]


def gerber_files(fmt, routed=True, bottom_ops=12):
    """返回 {文件名: 文本}。routed=False → 铜层没有 Track 段；bottom_ops 控制底层铜图形数量。"""
    f = fmt
    outline = polyline(f, 10, rect_pts(0, 0, BOARD_W, BOARD_H))
    top_secs = [("PolygonModel", region(f, rect_pts(2, 2, 6, 6))), ("Pad", flash(f, 11, PADS_TOP) + flash(f, 12, PADS_TOP[:4]))]
    if routed:
        top_secs += [("Via", flash(f, 13, VIAS)), ("Track", sum((polyline(f, 14, t) for t in TRACKS), []))]
    else:
        top_secs += [("Via", flash(f, 13, VIAS))]
    top = gerber(f, "TopLayer", [(10, "C,0.254"), (11, "R,1.0X0.6"), (12, "R,0.9X0.9"), (13, "C,0.61"), (14, "C,0.2")], top_secs)
    bot_pts = PADS_BOT[:bottom_ops]
    bot = gerber(f, "BottomLayer", [(10, "C,0.254"), (11, "R,1.0X0.6")], [("Pad", flash(f, 11, bot_pts))])
    silk_aps = [(10, "C,0.1524"), (11, "C,0.254"), (12, "C,0.0762")]
    silk_top = gerber(f, "TopSilkscreenLayer", silk_aps, [
        ("Text", polyline(f, 10, [(5, 35), (5, 36.5), (6.2, 36.5), (6.2, 35), (5, 35)]) + polyline(f, 10, [(8, 35), (9.5, 36.5)])),
        ("PolygonModel", polyline(f, 12, rect_pts(10, 24, 14, 27)) + polyline(f, 12, rect_pts(20, 24, 24, 27))),
        ("Circle", [f"G54D11*", f"G01X{f.c(30)}Y{f.c(25)}D02*", f"G03X{f.c(31.2)}Y{f.c(25)}I{f.c(0.6)}J{f.c(0)}D01*",
                    f"G03X{f.c(30)}Y{f.c(25)}I{f.c(-0.6)}J{f.c(0)}D01*"])])
    silk_bot = gerber(f, "BottomSilkscreenLayer", silk_aps[:1], [("Text", polyline(f, 10, [(5, 5), (5, 6.5), (6.2, 6.5)]))])
    mask_top = gerber(f, "TopSolderMaskLayer", [(10, "R,1.1X0.7"), (11, "C,0.71")], [("Pad", flash(f, 10, PADS_TOP)), ("Via", flash(f, 11, VIAS))])
    mask_bot = gerber(f, "BottomSolderMaskLayer", [(10, "R,1.1X0.7")], [("Pad", flash(f, 10, PADS_BOT[:bottom_ops]))])
    paste_top = gerber(f, "TopPasteMaskLayer", [(10, "R,0.9X0.5")], [("Pad", flash(f, 10, PADS_TOP))])
    doc = gerber(f, "DocumentLayer", [(10, "C,0.1")], [("Line", polyline(f, 10, [(1, 1), (2, 2)]))])
    out = {
        "Gerber_TopLayer.GTL": top, "Gerber_BottomLayer.GBL": bot,
        "Gerber_TopSilkscreenLayer.GTO": silk_top, "Gerber_BottomSilkscreenLayer.GBO": silk_bot,
        "Gerber_TopSolderMaskLayer.GTS": mask_top, "Gerber_BottomSolderMaskLayer.GBS": mask_bot,
        "Gerber_TopPasteMaskLayer.GTP": paste_top,
        "Gerber_BoardOutlineLayer.GKO": gerber(f, "BoardOutlineLayer", [(10, "C,0.254")], [("BoardOutline", outline)]),
        "Gerber_DocumentLayer.GDL": doc,
    }
    return out


def drill(kind, layer, tools, hits, slots=None, decimals=5):
    """kind: PLATED / NON_PLATED；tools: [(号, 孔径)]；hits: {号: [(x,y)]}；slots: {号: [((x1,y1),(x2,y2))]}"""
    fmt = f"{{:.{decimals}f}}"
    L = [f";TYPE={kind}", f";Layer: {layer}", f";{SYNTH_NOTE}", ";Gerber Generator version 0.3", "M48",
         "METRIC,LZ,0000.00000"]
    for n, d in tools:
        L += [f";Hole size {n} = {fmt.format(d)} METRIC", f"T{n:02d}C{fmt.format(d)}"]
    L += ["%", "G05", "G90"]
    for n, _d in tools:
        L.append(f"T{n:02d}")
        for x, y in hits.get(n, []):
            L.append(f"X{x:g}Y{y:g}")
        for (a, b) in (slots or {}).get(n, []):
            L.append(f"X{a[0]:g}Y{a[1]:g}G85X{b[0]:g}Y{b[1]:g}")
    L.append("M30")
    return "\n".join(L) + "\n"


def drill_files(with_via_file=True):
    thru = [(54.0, 8.0), (54.0, 10.0)]
    pth_hits = {1: VIAS, 3: thru}
    slots = {2: [((50.0, 36.0), (51.0, 36.0)), ((53.0, 36.0), (54.0, 36.0))]}
    pth_tools = [(1, 0.30505), (2, 0.6), (3, 1.50002)]
    out = {"Drill_PTH_Through.DRL": drill("PLATED", "PTH_Through", pth_tools, pth_hits, slots),
           "Drill_NPTH_Through.DRL": drill("NON_PLATED", "NPTH_Through", [(1, 0.24999), (2, 0.6), (3, 1.0)],
                                           {1: [(3.0, 3.0)], 2: [(57.0, 3.0), (57.0, 37.0)], 3: [(3.0, 37.0), (30.0, 37.0)]})}
    if with_via_file:
        out["Drill_PTH_Through_Via.DRL"] = drill("PLATED", "PTH_Through_Via", [(1, 0.30505)], {1: VIAS})
    return out


def zip_bytes(files):
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_STORED) as z:
        for name in sorted(files):
            zi = zipfile.ZipInfo(name, ZIP_TIME)
            zi.compress_type = zipfile.ZIP_STORED
            data = files[name]
            z.writestr(zi, data.encode("utf-8") if isinstance(data, str) else data)
    return buf.getvalue()


def build_new_zip():
    f = Fmt(4, 5)
    files = {**gerber_files(f), **drill_files(True)}
    files["Gerber_DrillDrawingLayer.GDD"] = gerber(f, "DrillDrawingLayer", [(10, "C,0.1")], [("Line", polyline(f, 10, [(1, 1), (2, 2)]))])
    files["FlyingProbeTesting.json"] = json.dumps({"synthetic": True, "note": SYNTH_NOTE})
    files["PCB下单必读.txt"] = "Synthetic fixture. Not a real order.\n"
    return zip_bytes(files)


def build_old_zip():
    f = Fmt(2, 6)
    files = {**gerber_files(f, routed=False, bottom_ops=6), **drill_files(False)}
    files["FlyingProbeTesting.json"] = json.dumps({"synthetic": True})
    files["PCB下单必读.txt"] = "Synthetic fixture. Not a real order.\n"
    return zip_bytes(files)


# ───────────────────────── BOM / 坐标（EDA 原生形态） ─────────────────────────
